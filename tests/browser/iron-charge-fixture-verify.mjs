import { chromium } from 'file:///C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';

const base = process.env.FIXTURE_URL ?? 'http://127.0.0.1:3014/iron-charge-fixture.html';
const outDir = path.resolve('tests/browser/iron-charge-evidence');
await fs.mkdir(outDir, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 960, height: 720 } });
const consoleErrors = [], pageErrors = [], requestFailures = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') consoleErrors.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => pageErrors.push(String(e))); page.on('requestfailed', (r) => requestFailures.push(`${r.url()} — ${r.failure()?.errorText ?? 'failed'}`));
await page.goto(base, { waitUntil: 'networkidle' });
await page.waitForFunction(() => Boolean(window.__ironChargeFixture));
const result = await page.evaluate(() => window.__ironChargeFixture);
await page.screenshot({ path: path.join(outDir, '01-full-fixture.png'), fullPage: true });
const final = { result, consoleErrors, pageErrors, requestFailures, browser: await browser.version() };
await fs.writeFile(path.join(outDir, 'fixture-result.json'), JSON.stringify(final, null, 2));
const failed = [];
if (!result.a.castAccepted || !result.a.impact || !(result.a.travelDistance < 3.5) || result.a.stunEligible || result.a.stunned || result.a.damage <= 0) failed.push('Case A');
if (!result.b.castAccepted || !result.b.impact || !(result.b.travelDistance >= 3.5) || !result.b.stunEligible || !result.b.stunned || Math.abs(result.b.stunExpiresAt - 1.5) > 0.001) failed.push('Case B');
if (result.c.attempts.some((x) => x.accepted) || !result.c.stunned) failed.push('Case C');
if (result.d.stunned || !result.d.movement.accepted || !result.d.basicAttack.accepted || !result.d.activeSkill.accepted) failed.push('Case D');
if (!result.e.impact || result.e.damage <= 0 || !result.e.stunEligible || result.e.stunned) failed.push('Case E');
if (!(result.basic.damage > 0) || result.basic.stunned || result.basic.knockback !== 0) failed.push('Basic Attack');
if (consoleErrors.length || pageErrors.length || requestFailures.length) failed.push('Browser diagnostics');
console.log(JSON.stringify({ status: failed.length ? 'FAIL' : 'PASS', failed, ...final }, null, 2));
await browser.close();
if (failed.length) process.exitCode = 1;
