import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'file:///C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';

const root = process.cwd();
const url = process.env.BERSERKER_FIXTURE_URL ?? 'http://127.0.0.1:3016/tests/browser/berserker-fixture.html';
const evidenceDir = path.join(root, 'tests', 'browser', 'berserker-evidence');
fs.mkdirSync(evidenceDir, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage();
const errors = [];
page.on('console', (message) => { if (message.type() === 'error' || message.type() === 'warning') errors.push(`console:${message.type()}:${message.text()}`); });
page.on('pageerror', (error) => errors.push(`pageerror:${error.message}`));
page.on('requestfailed', (request) => errors.push(`request:${request.url()}:${request.failure()?.errorText ?? 'failed'}`));
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForFunction(() => document.querySelector('#status')?.textContent === 'BERSERKER_FIXTURE_READY');
const payload = await page.evaluate(() => (window).__berserkerFixture);
await page.screenshot({ path: path.join(evidenceDir, '01-full-fixture.png'), fullPage: true });
fs.writeFileSync(path.join(evidenceDir, '01-full-fixture.json'), JSON.stringify({ payload, errors }, null, 2));
if (errors.length) throw new Error(`browser diagnostics: ${errors.join('; ')}`);
if (payload?.worldImported !== false) throw new Error('fixture world import flag invalid');
if (payload.cases.raging.actualTargetsHit !== 8) throw new Error('Earth Splitter target cap failed');
if (payload.cases.fury.actualTargetsHit !== 7 || payload.cases.fury.heal !== 50) throw new Error('Fury Harvest recovery failed');
if (payload.cases.trance.actualTargetsHit !== 8 || payload.cases.trance.frenzyGuard?.reductionPercent !== 6) throw new Error('Trance/Frenzy Guard failed');
if (!payload.cases.breakerFollowup.accepted || !payload.cases.breakerFollowup.consumed) throw new Error('Breaker Entry window failed');
if (!payload.cases.raging.results.some((item) => item.stunned)) throw new Error('Earth Splitter deterministic Stun missing');
if (payload.cases.raging.results.find((item) => item.id === 'target-8')?.stunned) throw new Error('stun immunity failed');
console.log(JSON.stringify({ status: 'PASS', errors, evidence: evidenceDir, payload }, null, 2));
await browser.close();
