import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const forbidden = /\b(Gatotkaca|Garda|Caroq|Anom|Srikandi|Jagawana|Resi|Pujangga|Pandita|Bajra|Capstone|Mastery)\b/i;
const evidence = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:3003/warrior-world.html?level=59&build=general');
  await page.getByRole('button', { name: /^continue$/i }).click();
  await page.waitForFunction(() => window.__warriorQA?.game?.started, { timeout: 60000 });
  await page.evaluate(() => { const g = window.__warriorQA.game; g.renderer.setAnimationLoop(null); cancelAnimationFrame(g.frame); });
  const check = async name => {
    const text = await page.locator('body').innerText();
    assert(!forbidden.test(text), `${name}: ${text.match(forbidden)?.[0]}`);
    evidence.push({ surface: name, forbiddenMatches: 0 });
  };
  await check('V2 HUD');
  await page.keyboard.press('k');
  await page.locator('.job-skill').waitFor();
  assert.equal(await page.locator('.js-node').count(), 30);
  await check('V2 K Warrior 30 nodes');
  await page.locator('.js-sidebar button').first().click();
  assert(await page.locator('.js-node').count() > 0);
  await check('V2 K Adventurer inherited');
  await page.keyboard.press('k');
  await page.keyboard.press('c');
  await page.locator('.character-dialog').waitFor();
  await check('V2 C overview');
  await page.getByRole('button', { name: 'Job view', exact: true }).click();
  await page.getByRole('region', { name: 'Job Architecture V2' }).waitFor();
  assert.match(await page.getByRole('region', { name: 'Job Architecture V2' }).innerText(), /Berserker.*Locked/s);
  await page.getByText('Job Architecture V2 · preview', { exact: true }).click();
  await check('V2 C full canonical architecture');
  assert.match(await page.getByRole('region', { name: 'Job Architecture V2' }).innerText(), /Assasin/);
  assert.equal(await page.getByRole('button', { name: /^Berserker$/ }).count(), 0);
  await mkdir('output/job-visibility', { recursive: true });
  await page.screenshot({ path: 'output/job-visibility/v2-character.png' });
  await page.keyboard.press('Escape');
  await page.keyboard.press('c');
  await page.keyboard.press('j');
  await page.locator('.quest-journal').waitFor();
  await check('V2 J quest journal');
  await page.keyboard.press('j');
  // Actual NPC dialog event, using the development-memory actor only.
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('lumenfall:npc', { detail: 'jaya-1' })));
  await page.locator('.npc-menu-dialog').waitFor();
  await check('V2 specialization NPC dialog');
  await page.getByRole('button', { name: 'Job', exact: true }).click();
  await page.locator('.class-panel').waitFor();
  await check('V2 Job/promotion preview');
  assert.equal(await page.locator('.class-panel .class-choice').count(), 0);
  await page.screenshot({ path: 'output/job-visibility/v2-job.png' });
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('lumenfall:npc', { detail: 'aruna-4' })));
  await page.locator('.npc-shop-list').waitFor();
  await check('V2 Equipment Merchant catalog');
  const item = page.locator('[data-item-hover="caroq-daggers"]').first();
  if (await item.count()) { await item.hover(); await page.getByRole('tooltip').waitFor(); await check('V2 legacy item tooltip'); }
  await context.close();
  const legacy = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const old = await legacy.newPage(); old.on('pageerror', e => errors.push(e.message));
  await old.goto('http://127.0.0.1:3003/warrior-world.html?architecture=legacy');
  await old.getByRole('button', { name: /^continue$/i }).click();
  await old.waitForFunction(() => window.__warriorQA?.game?.started, { timeout: 60000 });
  await old.evaluate(() => { const g=window.__warriorQA.game; g.renderer.setAnimationLoop(null); cancelAnimationFrame(g.frame); });
  await old.keyboard.press('k'); await old.locator('.job-skill').waitFor();
  assert.match(await old.locator('.job-skill').innerText(), /Gatotkaca \/ Garda/);
  evidence.push({ surface: 'Legacy K', progressionRetained: true });
  await old.keyboard.press('k');
  await old.evaluate(() => window.dispatchEvent(new CustomEvent('lumenfall:npc', { detail: 'jaya-1' })));
  await old.getByRole('button', { name: 'Job', exact: true }).click();
  await old.locator('.class-panel').waitFor();
  assert.match(await old.locator('.class-panel').innerText(), /Gatotkaca/);
  assert.equal(await old.locator('.class-choice:not(:disabled)').count(), 2);
  await old.screenshot({ path: 'output/job-visibility/legacy-job.png' });
  assert.equal(await old.evaluate(() => window.__warriorQA.game.hero.specialization), null);
  assert.deepEqual((await legacy.storageState()).origins, []);
  assert.deepEqual(errors, []);
  evidence.push({ surface: 'Legacy promotion', enabledChoices: 2, saveMigration: false });
  await writeFile('output/job-visibility/browser-evidence.json', JSON.stringify({ evidence, errors, memoryOnly: true }, null, 2));
  console.log('PASS', JSON.stringify(evidence));
} finally { await browser.close(); }
