import assert from 'node:assert/strict';
import { build } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const runtime = process.env.CODEX_NODE_MODULES || 'C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const { chromium } = await import(pathToFileURL(`${runtime}/playwright/index.mjs`).href);
const out = resolve('output/release-audit/blade-master-7a');
await mkdir(out, { recursive: true });
const built = await build({ configFile: false, logLevel: 'error', build: { write: false, minify: false, lib: { entry: resolve('tests/browser/blade-master-7a-fixture.ts'), formats: ['iife'], name: 'BladeMaster7AFixture' } } });
const code = (Array.isArray(built) ? built : [built]).flatMap((b) => b.output).find((c) => c.type === 'chunk').code;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errors.push(m.text()); });
await page.route('http://blade-master-7a.test/**', (route) => route.fulfill({ status: 200, contentType: route.request().url().includes('.bundle.js') ? 'application/javascript' : 'text/html', body: route.request().url().includes('.bundle.js') ? code : '<pre id="result"></pre><script type="module" src="/tests/browser/blade-master-7a-fixture.bundle.js"></script>' }));
await page.goto('http://blade-master-7a.test/tests/browser/blade-master-7a-fixture.html', { waitUntil: 'networkidle' });
await page.waitForFunction(() => Boolean(window.__bladeMaster7AFixture));
const payload = await page.evaluate(() => window.__bladeMaster7AFixture);
assert.deepEqual(errors, []);
assert.equal(payload.status, 'PASS');
assert.equal(payload.worldImported, false);
assert.equal(payload.exactSkillCount, 9);
assert.equal(payload.masteryActive, true);
assert.deepEqual(payload.twinAssaultHits.map((h) => h.hand), ['MAIN', 'OFF']);
assert.equal(payload.twinAssaultSharedWeightTotal, 1);
assert.equal(payload.dualCombinedWeaponAttack, 170);
assert.deepEqual(payload.dualBasicAlternation, ['MAIN', 'OFF', 'MAIN', 'OFF']);
assert.equal(payload.flowConsumed, true);
assert.equal(payload.flowAfter, false);
assert.equal(payload.counterflowStun.chance, 1);
assert.equal(payload.counterflowStun.pveDuration, 0.8);
assert.equal(payload.noTempoSystem, true);
await page.screenshot({ path: resolve(out, 'fixture.png'), fullPage: true });
await writeFile(resolve(out, 'results.json'), JSON.stringify({ status: 'PASS', payload, errors }, null, 2));
console.log(JSON.stringify({ status: 'PASS', payload, errors }, null, 2));
await browser.close();
